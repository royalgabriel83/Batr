// Writes apps/web/.env.local and apps/mobile/.env.local (both
// git-ignored) from the running local Supabase, for local development
// only. Skips a file that already exists unless --force is passed.
import { existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { readLocalSupabase } from "./local-supabase.mjs";

const force = process.argv.includes("--force");
const status = readLocalSupabase();

function write(path, lines) {
  const target = new URL(`../${path}`, import.meta.url);
  if (existsSync(target) && !force) {
    console.error(`${path} already exists. Re-run with --force to replace it.`);
    return;
  }
  writeFileSync(target, lines.join("\n"), { mode: 0o600 });
  console.log(`Wrote ${path} for local Supabase.`);
}

write("apps/web/.env.local", [
  "# Local development only. Generated by `pnpm env:local`. Never commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
  `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
  `CRON_SECRET=${randomBytes(32).toString("hex")}`,
  "",
]);

// The mobile app (Milestone 2) gets only public values: the anon key
// and the URLs. EXPO_PUBLIC_ values are built into the app, so the
// service key never goes here.
write("apps/mobile/.env.local", [
  "# Local development only. Generated by `pnpm env:local`. Never commit.",
  `EXPO_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `EXPO_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
  "EXPO_PUBLIC_API_URL=http://localhost:3000",
  "",
]);
