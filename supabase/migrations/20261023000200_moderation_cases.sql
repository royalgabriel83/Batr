-- "Completed" only follows a handover; a problem on a completed
-- agreement is its own line.
create or replace function private.agreement_event_written() returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_agreement public.agreements;
  v_kind text := case when new.action = 'handover' and new.to_status = 'completed' then 'agreement.completed' else 'agreement.' || new.action end;
  v_member uuid;
begin
  if new.action = 'create' then
    return null;
  end if;
  select * into v_agreement from public.agreements a where a.id = new.agreement_id;
  insert into public.messages (proposal_id, kind, system_event, actor_id)
  values (v_agreement.proposal_id, 'system', v_kind, new.actor_id);
  foreach v_member in array array[v_agreement.proposer_id, v_agreement.owner_id] loop
    if v_member is distinct from new.actor_id then
      perform private.notify(v_member, v_kind, v_agreement.proposal_id, new.actor_id);
    end if;
  end loop;
  return null;
end;
$$;

-- Risk (W2) ---------------------------------------------------------

create function private.report_risk(p_report public.reports) returns text
language sql stable
set search_path = ''
as $$
  select case
    when p_report.subject_type = 'agreement' or p_report.reason in ('scam', 'prohibited_item')
      or (select count(*) from public.reports r
          where r.member_id = p_report.member_id and r.created_at > now() - interval '30 days')
         >= private.safety_limit('repeatReports30Days') then 'high'
    when p_report.reason in ('harassment', 'misleading', 'contact_details') then 'medium'
    else 'low'
  end
$$;

create function private.risk_rank(p_risk text) returns integer
language sql immutable
set search_path = ''
as $$ select case p_risk when 'high' then 0 when 'medium' then 1 else 2 end $$;

