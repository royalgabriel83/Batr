-- D2: while paused, no handover, no new change and no change accepted.
create function private.agreement_not_paused() returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_paused uuid;
begin
  if tg_table_name = 'agreements' then
    if new.paused_report_id is not null and old.paused_report_id is not null
       and new.binding_version_id is distinct from old.binding_version_id then
      perform private.fail('CONFLICT', 409, '{"reason": "paused"}');
    end if;
    return new;
  end if;
  select a.paused_report_id into v_paused from public.agreements a where a.id = new.agreement_id;
  if v_paused is not null and (tg_table_name = 'handover_confirmations' or to_jsonb(new) ->> 'outcome' = 'pending') then
    perform private.fail('CONFLICT', 409, '{"reason": "paused"}');
  end if;
  return new;
end;
$$;

create trigger handover_confirmations_not_paused before insert on public.handover_confirmations
for each row execute function private.agreement_not_paused();
create trigger agreement_versions_not_paused before insert on public.agreement_versions
for each row execute function private.agreement_not_paused();
create trigger agreements_not_paused before update of binding_version_id on public.agreements
for each row execute function private.agreement_not_paused();

-- D3: a moderator may cancel an agreement from any open status.
create or replace function private.check_agreement_status_change() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status is distinct from old.status then
    if (old.status, new.status) not in (
      ('active', 'amendment_pending'), ('active', 'cancellation_requested'), ('active', 'completed'),
      ('amendment_pending', 'active'), ('cancellation_requested', 'active'), ('cancellation_requested', 'cancelled')
    ) and not (
      new.status = 'cancelled' and old.status in ('active', 'amendment_pending')
      and coalesce(current_setting('batr.moderation_cancel', true), '') = 'on'
    ) then
      raise exception using errcode = '23514', message = format('Agreement status change %s -> %s is not allowed.', old.status, new.status);
    end if;
    if new.status = 'completed'
      and (select count(*) from public.handover_confirmations h where h.agreement_id = new.id) <> 2 then
      raise exception using errcode = '23514', message = 'An agreement completes only when both parties have confirmed handover.';
    end if;
  end if;
  return new;
end;
$$;

