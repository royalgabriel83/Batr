-- W8: a senior moderator is also a moderator.
create or replace function private.require_moderator() returns uuid
language plpgsql stable
set search_path = ''
as $$
declare
  v_actor uuid := private.require_actor();
begin
  if not private.is_moderator(v_actor) then
    perform private.fail('NOT_FOUND', 404);
  end if;
  return v_actor;
end;
$$;

