create or replace function private.moderation_summary_json(p_report public.reports) returns jsonb
language sql stable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p_report.id,
    'case_number', p_report.case_number,
    'subject_type', p_report.subject_type,
    'label', private.report_label(p_report),
    'reason', p_report.reason,
    'details', p_report.details,
    'status', case when p_report.status = 'reviewed' then 'closed'
                   when p_report.assignee_id is not null then 'in_review' else 'open' end,
    'risk', private.report_risk(p_report),
    'reporter_name', case when p_report.reporter_id is null then 'BATR (automatic check)' else private.display_name(p_report.reporter_id) end,
    'automatic', p_report.reporter_id is null,
    'member_name', private.display_name(p_report.member_id),
    'assignee_name', case when p_report.assignee_id is null then null else private.display_name(p_report.assignee_id) end,
    'assigned_to_me', p_report.assignee_id = (select auth.uid()),
    'created_at', p_report.created_at,
    'reviewed_at', p_report.reviewed_at)
$$;

-- W3: high risk first, then oldest. Filters and search narrow it.
drop function public.moderation_queue();
create function public.moderation_queue(
  p_type text default null,
  p_risk text default null,
  p_status text default 'active',
  p_assigned text default null,
  p_search text default null
) returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_moderator();
  v_search text := nullif(private.trim_text(coalesce(p_search, '')), '');
  -- "152", "0152", "#152" or "Case 0152"; anything else is text, so a
  -- long run of digits can't overflow the cast.
  v_number bigint := case when v_search ~* '^(case\s*)?#?\d{1,9}$'
                          then regexp_replace(v_search, '\D', '', 'g')::bigint end;
begin
  if p_type is not null and p_type not in ('offer', 'member', 'message', 'agreement')
     or p_risk is not null and p_risk not in ('high', 'medium', 'low')
     or coalesce(p_status, 'active') not in ('active', 'open', 'in_review', 'closed')
     or p_assigned is not null and p_assigned not in ('me', 'unassigned') then
    perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"filter": "invalid"}}');
  end if;
  return coalesce((
    select jsonb_agg(c.summary order by private.risk_rank(c.summary ->> 'risk'), c.created_at, c.id)
    from (
      select private.moderation_summary_json(r) as summary, r.created_at, r.id
      from public.reports r
      where not private.report_involves(r, v_actor)
        and (p_type is null or r.subject_type = p_type)
        and case coalesce(p_status, 'active')
              when 'active' then r.status = 'open'
              when 'open' then r.status = 'open' and r.assignee_id is null
              when 'in_review' then r.status = 'open' and r.assignee_id is not null
              else r.status = 'reviewed' end
        and (p_assigned is null
             or (p_assigned = 'me' and r.assignee_id = v_actor)
             or (p_assigned = 'unassigned' and r.assignee_id is null))
        and (v_search is null
             or r.case_number = v_number
             or private.report_label(r) ilike '%' || v_search || '%'
             or private.display_name(r.member_id) ilike '%' || v_search || '%'
             or private.display_name(r.reporter_id) ilike '%' || v_search || '%')
      order by r.created_at desc
      limit 200
    ) c
    where p_risk is null or c.summary ->> 'risk' = p_risk), '[]');
end;
$$;

-- W5: one case, with what it points to and the member's history as
-- counts only.
create or replace function public.moderation_report(p_report_id uuid) returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_moderator();
  v_report public.reports;
  v_message public.messages;
  v_context integer := private.safety_limit('contextMessages');
  v_subject jsonb;
  v_offer public.offers;
  v_agreement public.agreements;
  v_open boolean;
begin
  select * into v_report from public.reports r where r.id = p_report_id;
  if not found or private.report_involves(v_report, v_actor) then
    perform private.fail('NOT_FOUND', 404);
  end if;
  v_open := v_report.status = 'open';
  case v_report.subject_type
    when 'offer' then
      select * into v_offer from public.offers o where o.id = v_report.offer_id;
      v_subject := jsonb_build_object('offer', private.offer_json(v_report.offer_id) - 'owner_id');
    when 'member' then
      v_subject := jsonb_build_object('offers', coalesce((
        select jsonb_agg(jsonb_build_object('id', o.id, 'title', o.title, 'status', o.status, 'removed_at', o.removed_at)
                         order by o.updated_at desc)
        from public.offers o where o.owner_id = v_report.member_id and o.status <> 'draft'), '[]'));
    when 'agreement' then
      select * into v_agreement from public.agreements a where a.id = v_report.agreement_id;
      v_subject := jsonb_build_object('agreement', jsonb_build_object(
        'status', v_agreement.status,
        'paused', v_agreement.paused_report_id is not null,
        'created_at', v_agreement.created_at,
        'completed_at', v_agreement.completed_at,
        'cancelled_at', v_agreement.cancelled_at,
        'reporter_role', case when v_report.reporter_id = v_agreement.owner_id then 'owner' else 'proposer' end,
        'terms', (select jsonb_build_object('number', v.number, 'gives', v.gives, 'gets', v.gets,
                    'cash', case when v.cash_naira is null then null
                                 else jsonb_build_object('amount_naira', v.cash_naira, 'payer', v.cash_payer) end)
                  from public.agreement_versions v where v.id = v_agreement.binding_version_id),
        'confirmed', (select coalesce(jsonb_agg(jsonb_build_object(
                        'role', case when h.party_id = v_agreement.owner_id then 'owner' else 'proposer' end,
                        'confirmed_at', h.confirmed_at) order by h.confirmed_at), '[]')
                      from public.handover_confirmations h where h.agreement_id = v_agreement.id),
        'events', (select coalesce(jsonb_agg(jsonb_build_object(
                     'action', e.action,
                     'by', case when e.actor_id is null then null when e.actor_id = v_agreement.owner_id then 'owner' else 'proposer' end,
                     'created_at', e.created_at) order by e.id), '[]')
                   from public.agreement_events e where e.agreement_id = v_agreement.id),
        'reply', v_report.reply,
        'replied_at', v_report.replied_at));
    else
      select * into v_message from public.messages m where m.id = v_report.message_id;
      v_subject := jsonb_build_object('messages', (
        select coalesce(jsonb_agg(jsonb_build_object(
          'id', m.id, 'kind', m.kind, 'body', m.body, 'event', m.system_event,
          'from', case when m.sender_id = v_report.member_id then 'reported'
                       when m.sender_id is null then null else 'other' end,
          'reported', m.id = v_message.id, 'created_at', m.created_at) order by m.id), '[]')
        from (
          (select * from public.messages m where m.proposal_id = v_message.proposal_id and m.id < v_message.id order by m.id desc limit v_context)
          union all
          (select * from public.messages m where m.id = v_message.id)
          union all
          (select * from public.messages m where m.proposal_id = v_message.proposal_id and m.id > v_message.id order by m.id limit v_context)
        ) m),
        'other_name', (select private.display_name(case when p.proposer_id = v_report.member_id then p.owner_id else p.proposer_id end)
                       from public.proposals p where p.id = v_message.proposal_id));
  end case;
  return private.moderation_summary_json(v_report) || jsonb_build_object(
    'subject', v_subject,
    'member_suspended', private.is_suspended(v_report.member_id),
    -- Counts only (W5): never other cases' content.
    'member_counts', jsonb_build_object(
      'reports_30_days', (select count(*) from public.reports r
                          where r.member_id = v_report.member_id and r.created_at > now() - interval '30 days'),
      'earlier_actions', (select count(*) from public.moderation_actions a
                          where a.member_id = v_report.member_id and a.action not in ('assign', 'unsuspend', 'appeal_upheld', 'appeal_lifted')
                            and a.report_id is distinct from v_report.id),
      'breaches', (select count(*) from public.moderation_actions a
                   where a.member_id = v_report.member_id and a.action = 'record_breach')),
    -- This case's own log.
    'history', coalesce((
      select jsonb_agg(jsonb_build_object(
        'action', a.action, 'note', a.note, 'moderator_name', private.display_name(a.moderator_id), 'created_at', a.created_at)
        order by a.id desc)
      from public.moderation_actions a where a.report_id = v_report.id), '[]'),
    'actions', jsonb_build_object(
      'take', v_open and v_report.assignee_id is distinct from v_actor,
      'dismiss', v_open and v_report.subject_type <> 'agreement',
      'remove_offer', v_open and v_report.subject_type = 'offer' and v_offer.status is distinct from 'closed',
      'warn', v_open and v_report.subject_type in ('member', 'message', 'agreement'),
      'suspend', v_open and not private.is_suspended(v_report.member_id),
      'resume', v_open and v_report.subject_type = 'agreement',
      'cancel_agreement', v_open and v_report.subject_type = 'agreement'
                          and v_agreement.status in ('active', 'amendment_pending', 'cancellation_requested'),
      'record_breach', v_open and v_report.subject_type = 'agreement'));
end;
$$;

-- W4: take a case; another moderator can take it over. Logged.
create function public.moderation_assign(p_report_id uuid) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_moderator();
  v_report public.reports;
begin
  select * into v_report from public.reports r where r.id = p_report_id for update;
  if not found or private.report_involves(v_report, v_actor) then
    perform private.fail('NOT_FOUND', 404);
  end if;
  if v_report.status <> 'open' then
    perform private.fail('CONFLICT', 409, '{"reason": "already_reviewed"}');
  end if;
  if v_report.assignee_id is distinct from v_actor then
    update public.reports r set assignee_id = v_actor, assigned_at = now() where r.id = v_report.id;
    insert into public.moderation_actions (moderator_id, action, report_id, offer_id, member_id, agreement_id, note)
    values (v_actor, 'assign', v_report.id, v_report.offer_id, v_report.member_id, v_report.agreement_id,
            case when v_report.assignee_id is null then 'Took this case.'
                 else 'Took over this case from ' || private.display_name(v_report.assignee_id) || '.' end);
  end if;
  return public.moderation_report(v_report.id);
end;
$$;

-- W6 and D3: one decision closes a case. `p_target` picks the member
-- for warn, suspend and record_breach on an exchange problem.
drop function public.moderation_act(uuid, text, text, uuid);
create function public.moderation_act(
  p_report_id uuid, p_action text, p_note text, p_idempotency_key uuid default null, p_target text default 'reported'
) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_moderator();
  v_stored jsonb;
  v_report public.reports;
  v_note text;
  v_offer public.offers;
  v_agreement public.agreements;
  v_from text;
  v_member uuid;
  v_allowed jsonb;
  v_response jsonb;
begin
  v_stored := private.idempotency_begin(
    v_actor, p_idempotency_key, 'POST /api/v1/moderation/reports/:id/actions', p_report_id,
    private.request_hash(jsonb_build_object('action', p_action, 'note', p_note, 'target', p_target)));
  if v_stored is not null then
    return v_stored;
  end if;
  select * into v_report from public.reports r where r.id = p_report_id for update;
  if not found or private.report_involves(v_report, v_actor) then
    perform private.fail('NOT_FOUND', 404);
  end if;
  if v_report.status <> 'open' then
    perform private.fail('CONFLICT', 409, '{"reason": "already_reviewed"}');
  end if;
  if p_action is null or p_action not in ('dismiss', 'remove_offer', 'suspend', 'warn', 'resume', 'cancel_agreement', 'record_breach')
     or p_target is null or p_target not in ('reported', 'reporter')
     or (p_target = 'reporter' and (v_report.subject_type <> 'agreement' or p_action not in ('warn', 'suspend', 'record_breach'))) then
    perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"action": "invalid"}}');
  end if;
  v_allowed := public.moderation_report(v_report.id) -> 'actions';
  if p_action not in ('suspend', 'warn', 'record_breach') or p_target = 'reported' then
    if not coalesce((v_allowed ->> p_action)::boolean, false) then
      perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"action": "invalid"}}');
    end if;
  end if;
  v_note := private.check_note(p_note);
  v_member := case when p_target = 'reporter' then v_report.reporter_id else v_report.member_id end;
  if v_report.subject_type = 'agreement' then
    select * into v_agreement from public.agreements a where a.id = v_report.agreement_id for update;
  end if;

  if p_action = 'remove_offer' then
    select * into v_offer from public.offers o where o.id = v_report.offer_id for update;
    if v_offer.status = 'closed' then
      perform private.fail('CONFLICT', 409, '{"reason": "offer_closed"}');
    end if;
    -- Closing declines its open proposals (D2 trigger).
    update public.offers o set status = 'closed', closed_at = now(), removed_at = now() where o.id = v_offer.id;
    perform private.audit(v_actor, private.bump_offer(v_offer.id, false), 'remove', v_offer.status, 'closed');
  elsif p_action = 'suspend' then
    if private.is_suspended(v_member) then
      perform private.fail('CONFLICT', 409, '{"reason": "already_suspended"}');
    end if;
    insert into public.member_suspensions (member_id, suspended_by, report_id) values (v_member, v_actor, v_report.id);
  elsif p_action = 'warn' then
    insert into public.member_warnings (member_id, report_id) values (v_member, v_report.id);
  end if;

  -- An exchange problem: lift the pause, or cancel the agreement.
  if v_report.subject_type = 'agreement' then
    v_from := v_agreement.status;
    if p_action = 'cancel_agreement' then
      update public.agreement_versions v set outcome = 'withdrawn', resolved_at = now()
      where v.agreement_id = v_agreement.id and v.outcome = 'pending';
      update public.cancellation_requests c set outcome = 'accepted', resolved_by = v_actor, resolved_at = now()
      where c.agreement_id = v_agreement.id and c.outcome is null;
      update public.agreements a set paused_report_id = null where a.id = v_agreement.id;
      perform set_config('batr.moderation_cancel', 'on', true);
      v_agreement := private.agreement_set(v_agreement.id, 'cancelled');
      perform set_config('batr.moderation_cancel', 'off', true);
      perform private.agreement_event(v_agreement, null, 'moderation_cancel', v_from);
    else
      update public.agreements a set paused_report_id = null, revision = a.revision + 1, updated_at = now()
      where a.id = v_agreement.id
      returning * into v_agreement;
      perform private.agreement_event(v_agreement, null, 'problem_reviewed', v_from);
    end if;
  end if;

  insert into public.moderation_actions (moderator_id, action, report_id, offer_id, member_id, agreement_id, note)
  values (v_actor, p_action, v_report.id, v_report.offer_id, v_member, v_report.agreement_id, v_note);
  update public.reports r set status = 'reviewed', reviewed_at = now(), assignee_id = coalesce(r.assignee_id, v_actor),
    assigned_at = coalesce(r.assigned_at, now())
  where r.id = v_report.id;
  v_response := public.moderation_report(v_report.id);
  perform private.idempotency_finish(v_actor, p_idempotency_key, 200, v_response, v_report.id);
  return v_response;
end;
$$;

-- W8: only a senior moderator lifts a suspension someone else made.
create or replace function public.moderation_unsuspend(p_suspension_id uuid, p_note text, p_idempotency_key uuid default null) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_moderator();
  v_stored jsonb;
  v_suspension public.member_suspensions;
  v_note text;
  v_response jsonb;
begin
  v_stored := private.idempotency_begin(
    v_actor, p_idempotency_key, 'POST /api/v1/moderation/suspensions/:id/lift', p_suspension_id,
    private.request_hash(jsonb_build_object('note', p_note)));
  if v_stored is not null then
    return v_stored;
  end if;
  select * into v_suspension from public.member_suspensions s where s.id = p_suspension_id for update;
  if not found or v_suspension.member_id = v_actor then
    perform private.fail('NOT_FOUND', 404);
  end if;
  if v_suspension.lifted_at is not null then
    perform private.fail('CONFLICT', 409, '{"reason": "already_lifted"}');
  end if;
  if v_suspension.suspended_by <> v_actor and not private.has_role(v_actor, 'senior_moderator') then
    perform private.fail('FORBIDDEN', 403, '{"reason": "senior_only"}');
  end if;
  v_note := private.check_note(p_note);
  update public.member_suspensions s set lifted_at = now(), lifted_by = v_actor where s.id = v_suspension.id;
  insert into public.moderation_actions (moderator_id, action, member_id, note)
  values (v_actor, 'unsuspend', v_suspension.member_id, v_note);
  v_response := jsonb_build_object('lifted', true);
  perform private.idempotency_finish(v_actor, p_idempotency_key, 200, v_response, v_suspension.id);
  return v_response;
end;
$$;

-- W9: a senior moderator records an appeal's outcome (by email for now).
create function public.moderation_record_appeal(p_suspension_id uuid, p_outcome text, p_note text, p_idempotency_key uuid default null) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_moderator();
  v_stored jsonb;
  v_suspension public.member_suspensions;
  v_note text;
  v_response jsonb;
begin
  v_stored := private.idempotency_begin(
    v_actor, p_idempotency_key, 'POST /api/v1/moderation/suspensions/:id/appeal', p_suspension_id,
    private.request_hash(jsonb_build_object('outcome', p_outcome, 'note', p_note)));
  if v_stored is not null then
    return v_stored;
  end if;
  if not private.has_role(v_actor, 'senior_moderator') then
    perform private.fail('FORBIDDEN', 403, '{"reason": "senior_only"}');
  end if;
  select * into v_suspension from public.member_suspensions s where s.id = p_suspension_id for update;
  if not found or v_suspension.member_id = v_actor then
    perform private.fail('NOT_FOUND', 404);
  end if;
  if p_outcome is null or p_outcome not in ('upheld', 'lifted') then
    perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"outcome": "invalid"}}');
  end if;
  if v_suspension.lifted_at is not null or v_suspension.appeal_outcome is not null then
    perform private.fail('CONFLICT', 409, '{"reason": "already_decided"}');
  end if;
  v_note := private.check_note(p_note);
  update public.member_suspensions s
  set appeal_outcome = p_outcome, appeal_decided_at = now(),
      lifted_at = case when p_outcome = 'lifted' then now() else s.lifted_at end,
      lifted_by = case when p_outcome = 'lifted' then v_actor else s.lifted_by end
  where s.id = v_suspension.id;
  insert into public.moderation_actions (moderator_id, action, member_id, report_id, note)
  values (v_actor, 'appeal_' || p_outcome, v_suspension.member_id, v_suspension.report_id, v_note);
  v_response := jsonb_build_object('outcome', p_outcome);
  perform private.idempotency_finish(v_actor, p_idempotency_key, 200, v_response, v_suspension.id);
  return v_response;
end;
$$;

