-- Exchange problems (D1–D6) -----------------------------------------------

-- What the agreement page shows about a problem: whether the viewer
-- can report one, and the open or latest one, without saying who
-- reported it to the other member.
create function private.agreement_problem_json(p_agreement public.agreements, p_viewer uuid) returns jsonb
language sql stable
set search_path = ''
as $$
  select jsonb_build_object(
    'can_report', p_viewer in (p_agreement.proposer_id, p_agreement.owner_id)
      and (p_agreement.status in ('active', 'amendment_pending', 'cancellation_requested')
           or (p_agreement.status = 'completed'
               and p_agreement.completed_at > now() - make_interval(days => private.safety_limit('problemDaysAfterCompletion'))))
      and not exists (select 1 from public.reports r where r.agreement_id = p_agreement.id and r.status = 'open'),
    'paused', p_agreement.paused_report_id is not null,
    'current', (
      select jsonb_build_object(
        'status', r.status,
        'reason', case when r.reporter_id = p_viewer then r.reason else null end,
        'reported_by_you', r.reporter_id = p_viewer,
        'created_at', r.created_at,
        'reviewed_at', r.reviewed_at,
        'can_reply', r.status = 'open' and r.reporter_id <> p_viewer and r.reply is null,
        'replied', r.reply is not null)
      from public.reports r
      where r.agreement_id = p_agreement.id
      order by r.created_at desc limit 1))
$$;

create or replace function private.agreement_json(p_agreement_id uuid, p_viewer uuid) returns jsonb
language sql stable
set search_path = ''
as $$
  select private.agreement_core_json(a, p_viewer) || jsonb_build_object(
    'versions', (select jsonb_agg(private.agreement_version_json(v) order by v.number)
                 from public.agreement_versions v where v.agreement_id = a.id),
    'confirmations', (select coalesce(jsonb_agg(jsonb_build_object(
                        'party_id', h.party_id, 'version_id', h.version_id, 'confirmed_at', h.confirmed_at)
                        order by h.confirmed_at), '[]')
                      from public.handover_confirmations h where h.agreement_id = a.id),
    'cancellation', (select private.cancellation_request_json(c) from public.cancellation_requests c
                     where c.agreement_id = a.id order by c.created_at desc limit 1),
    'listing_changed', (select jsonb_array_length(private.changed_items(v.gives || v.gets)) > 0
                        from public.agreement_versions v where v.id = a.binding_version_id),
    'pending_changed_offer_ids', coalesce((
      select private.changed_items(private.new_items(p, b))
      from public.agreement_versions p, public.agreement_versions b
      where p.agreement_id = a.id and p.outcome = 'pending' and b.id = a.binding_version_id), '[]'),
    'fee', private.agreement_fee_json(a.offer_id),
    'my_listed_offers', (
      select coalesce(jsonb_agg(jsonb_build_object('id', o.id, 'title', o.title) order by o.title), '[]')
      from public.agreement_versions v
      cross join lateral jsonb_array_elements(v.gives || v.gets) i
      join public.offers o on o.id = (i ->> 'offer_id')::uuid
      where v.id = a.binding_version_id and i ->> 'kind' = 'offer'
        and o.owner_id = p_viewer and o.status in ('active', 'paused')
    ),
    'gives_choices', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', o.id, 'title', o.title,
        'thumb_path', (select ph.thumb_path from public.offer_photos ph where ph.offer_id = o.id order by ph.position limit 1)
      ) order by o.published_at desc), '[]')
      from public.offers o
      where o.owner_id = a.proposer_id and o.status = 'active' and a.status = 'active'
    ),
    'problem', private.agreement_problem_json(a, p_viewer)
  )
  from public.agreements a
  where a.id = p_agreement_id
$$;

-- The pause shows on list rows too.
create or replace function private.agreement_core_json(p_agreement public.agreements, p_viewer uuid) returns jsonb
language sql stable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p_agreement.id,
    'proposal_id', p_agreement.proposal_id,
    'offer_id', p_agreement.offer_id,
    'status', p_agreement.status,
    'revision', p_agreement.revision,
    'created_at', p_agreement.created_at,
    'updated_at', p_agreement.updated_at,
    'completed_at', p_agreement.completed_at,
    'cancelled_at', p_agreement.cancelled_at,
    'viewer_role', case when p_viewer = p_agreement.owner_id then 'owner' else 'proposer' end,
    'proposer', private.member_json(p_agreement.proposer_id),
    'owner', private.member_json(p_agreement.owner_id),
    'offer', (select jsonb_build_object('id', o.id, 'title', o.title, 'status', o.status)
              from public.offers o where o.id = p_agreement.offer_id),
    'binding_version_id', p_agreement.binding_version_id,
    'confirmed_by', (select coalesce(jsonb_agg(h.party_id order by h.confirmed_at), '[]')
                     from public.handover_confirmations h where h.agreement_id = p_agreement.id),
    'pending_by', (select v.proposed_by from public.agreement_versions v
                   where v.agreement_id = p_agreement.id and v.outcome = 'pending'),
    'cancel_requested_by', (select c.requested_by from public.cancellation_requests c
                            where c.agreement_id = p_agreement.id and c.outcome is null),
    'paused', p_agreement.paused_report_id is not null
  )
$$;

-- D1, D2, D4, D5: report a problem. An open agreement is paused.
create function public.agreement_problem_report(
  p_agreement_id uuid, p_reason text, p_details text, p_idempotency_key uuid default null
) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_actor();
  v_stored jsonb;
  v_details text := private.trim_text(coalesce(p_details, ''));
  v_agreement public.agreements;
  v_report public.reports;
  v_from text;
  v_response jsonb;
begin
  v_stored := private.idempotency_begin(
    v_actor, p_idempotency_key, 'POST /api/v1/agreements/:id/problem', p_agreement_id,
    private.request_hash(jsonb_build_object('reason', p_reason, 'details', p_details)));
  if v_stored is not null then
    return v_stored;
  end if;
  v_agreement := private.lock_agreement(p_agreement_id, v_actor, false);
  if p_reason is null or not (p_reason = any (private.problem_reasons())) then
    perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"reason": "invalid"}}');
  end if;
  if char_length(v_details) not between private.safety_limit('problemDetailsMin') and private.safety_limit('detailsMax') then
    perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"details": "length"}}');
  end if;
  if not coalesce((private.agreement_problem_json(v_agreement, v_actor) ->> 'can_report')::boolean, false) then
    if exists (select 1 from public.reports r where r.agreement_id = v_agreement.id and r.status = 'open') then
      perform private.fail('CONFLICT', 409, '{"reason": "already_reported"}');
    end if;
    perform private.fail('CONFLICT', 409, jsonb_build_object('reason', 'status_changed', 'current_status', v_agreement.status));
  end if;
  perform pg_advisory_xact_lock(hashtextextended('problem_report:' || v_actor::text, 0));
  if (select count(*) from public.reports r
      where r.reporter_id = v_actor and r.subject_type = 'agreement' and r.created_at > now() - interval '30 days')
     >= private.safety_limit('problemsPer30Days') then
    perform private.fail('RATE_LIMITED', 429);
  end if;
  insert into public.reports (reporter_id, subject_type, agreement_id, member_id, reason, details)
  values (v_actor, 'agreement', v_agreement.id,
          case when v_actor = v_agreement.owner_id then v_agreement.proposer_id else v_agreement.owner_id end,
          p_reason, v_details)
  returning * into v_report;
  v_from := v_agreement.status;
  update public.agreements a
  set paused_report_id = case when a.status in ('completed', 'cancelled') then null else v_report.id end,
      revision = a.revision + 1, updated_at = now()
  where a.id = v_agreement.id
  returning * into v_agreement;
  perform private.agreement_event(v_agreement, null, 'problem_reported', v_from);
  v_response := private.agreement_json(v_agreement.id, v_actor);
  perform private.idempotency_finish(v_actor, p_idempotency_key, 201, v_response, v_agreement.id);
  return v_response;
end;
$$;

-- D2: the other member adds their side, once.
create function public.agreement_problem_reply(p_agreement_id uuid, p_reply text, p_idempotency_key uuid default null) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.require_actor();
  v_stored jsonb;
  v_reply text := private.trim_text(coalesce(p_reply, ''));
  v_agreement public.agreements;
  v_report public.reports;
  v_response jsonb;
begin
  v_stored := private.idempotency_begin(
    v_actor, p_idempotency_key, 'POST /api/v1/agreements/:id/problem/reply', p_agreement_id,
    private.request_hash(jsonb_build_object('reply', p_reply)));
  if v_stored is not null then
    return v_stored;
  end if;
  v_agreement := private.lock_agreement(p_agreement_id, v_actor, false);
  select * into v_report from public.reports r
  where r.agreement_id = v_agreement.id and r.status = 'open' for update;
  if not found or v_report.reporter_id = v_actor then
    perform private.fail('CONFLICT', 409, '{"reason": "no_problem"}');
  end if;
  if v_report.reply is not null then
    perform private.fail('CONFLICT', 409, '{"reason": "already_replied"}');
  end if;
  if char_length(v_reply) not between 1 and private.safety_limit('problemReplyMax') then
    perform private.fail('VALIDATION_FAILED', 422, '{"fields": {"reply": "length"}}');
  end if;
  update public.reports r set reply = v_reply, replied_at = now() where r.id = v_report.id;
  v_response := private.agreement_json(v_agreement.id, v_actor);
  perform private.idempotency_finish(v_actor, p_idempotency_key, 200, v_response, v_agreement.id);
  return v_response;
end;
$$;

