-- Milestone 8: moderation workspace and exchange problems
-- (specs/milestone-8-moderation-and-disputes.md, W1–W10 and D1–D6 as
-- approved by the owner on 2026-10-23).
--
-- Every report is a case: it gains a case number, a risk, an assignee,
-- and a new subject, an agreement (an exchange problem). A problem on an
-- open agreement pauses handover and changes for both members, enforced
-- by triggers here, until a moderator decides. Moderators see a
-- member's history as counts only. A senior moderator role decides
-- appeals and lifts other moderators' suspensions. BATR never moves,
-- holds or refunds money; no outcome here touches money.

