create or replace function private.report_label(p_report public.reports) returns text
language sql stable
set search_path = ''
as $$
  select case p_report.subject_type
    when 'offer' then coalesce((select o.title from public.offers o where o.id = p_report.offer_id), 'An offer')
    when 'member' then private.display_name(p_report.member_id)
    when 'agreement' then 'An exchange on ' || coalesce((
      select o.title from public.agreements a join public.offers o on o.id = a.offer_id where a.id = p_report.agreement_id), 'an offer')
    else 'A message from ' || private.display_name(p_report.member_id)
